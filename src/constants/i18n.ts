export type TranslationKey = keyof typeof translations.fr;

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  params?: Record<string, string | number | null | undefined>,
) {
  let template = String(translations[language][key] ?? translations.fr[key]);
  if (!params) return template;

  for (const [paramKey, paramValue] of Object.entries(params)) {
    template = template.replace(
      new RegExp(`{{${paramKey}}}`, "g"),
      String(paramValue ?? ""),
    );
  }

  return template;
}

export function feedingModeLabelKey(mode: FeedingMode): TranslationKey {
  switch (mode) {
    case "bottle":
      return "feeding_mode.bottle";
    case "mixed":
      return "feeding_mode.mixed";
    default:
      return "feeding_mode.breastfeeding";
  }
}

